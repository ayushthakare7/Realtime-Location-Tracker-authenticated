const express = require('express');
const auth = require('../middleware/authMiddleware');
const friendsController = require('../controllers/friendshipController');
const historyController = require('../controllers/historyController');
const mapAssistantController = require('../controllers/mapAssistantController');
const locationQueryController = require('../controllers/locationQueryController');
const router = express.Router();
router.use(auth);
router.get('/friends', friendsController.listFriends);
router.delete('/friends/:id', friendsController.removeFriend);
router.post('/friends/request', friendsController.sendFriendRequest);
router.post('/friends/requests/:id/respond', friendsController.respondToRequest);
router.patch('/sharing', friendsController.setSharing);
router.patch('/history', historyController.setHistory);
router.get('/history', historyController.history);
router.delete('/history', historyController.deleteHistory);
router.post('/ask', locationQueryController.ask);
router.get('/ask-status/:taskId', mapAssistantController.askRagTaskStatus);
module.exports = router;
